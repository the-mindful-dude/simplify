/**
 * Canonical token build script for @simplify-dev/tokens.
 *
 * Reads src/source/tokens.json (the only hand-authored source of raw values) and
 * regenerates every artifact under src/outputs/. Run with:
 *
 *   pnpm --filter @simplify-dev/tokens exec node src/generators/generate.mjs
 *
 * The script has no dependencies and is framework-independent. It emits the CSS
 * custom properties and the typed TypeScript source consumed by src/index.ts,
 * so generated values can never drift from the canonical source.
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const generatorDir = dirname(fileURLToPath(import.meta.url));
const sourcePath = resolve(generatorDir, '../source/tokens.json');
const outputDir = resolve(generatorDir, '../outputs');
const cssPath = resolve(outputDir, 'tokens.css');
const typescriptPath = resolve(outputDir, 'tokens.generated.ts');

const source = JSON.parse(readFileSync(sourcePath, 'utf8'));

/** Convert camelCase token keys into their kebab-case CSS custom-property form. */
function toKebabCase(key) {
  return key.replace(/([A-Z])/g, '-$1').toLowerCase();
}

/** Prettier-compatible, deterministic serializer for the generated TS module. */
function serialize(value, level) {
  const pad = '  '.repeat(level);
  const childPad = '  '.repeat(level + 1);

  if (Array.isArray(value)) {
    if (value.length === 0) return '[]';
    return `[\n${value.map((item) => `${childPad}${serialize(item, level + 1)},`).join('\n')}\n${pad}]`;
  }

  if (value !== null && typeof value === 'object') {
    const keys = Object.keys(value);
    if (keys.length === 0) return '{}';
    return `{\n${keys
      .map((key) => {
        const name = /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(key) ? key : `'${key}'`;
        return `${childPad}${name}: ${serialize(value[key], level + 1)},`;
      })
      .join('\n')}\n${pad}}`;
  }

  if (typeof value === 'string') {
    return `'${value.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
  }

  return JSON.stringify(value);
}

const cssLines = [];
for (const [group, values] of Object.entries(source)) {
  for (const [key, value] of Object.entries(values)) {
    cssLines.push(`  --sd-${toKebabCase(group)}-${toKebabCase(key)}: ${value};`);
  }
}

const css = `:root,\n[data-sd-theme='dark'] {\n${cssLines.join('\n')}\n}\n`;
const typescript = `// AUTO-GENERATED from src/source/tokens.json by src/generators/generate.mjs.\n// Do not edit this file directly; change the canonical JSON source and regenerate.\nexport const tokenSource = ${serialize(source, 0)} as const;\n`;

mkdirSync(outputDir, { recursive: true });
writeFileSync(cssPath, css, 'utf8');
writeFileSync(typescriptPath, typescript, 'utf8');

process.stdout.write(
  `Generated ${cssPath} and ${typescriptPath} (${cssLines.length} custom properties).\n`,
);
