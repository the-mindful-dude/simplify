import { promises as fs } from 'node:fs';
import { dirname, join } from 'node:path';
import type { Command } from './index.js';
import { info, CliError } from '../cli.js';
import type {
  AssetCategory,
  AssetManifest,
  DocumentationReferences,
  LibraryManifest,
  PublishingConfiguration,
} from '@simplify-dev/schemas';
import { validateAssetManifest, validateLibraryManifest } from '@simplify-dev/registry';

const ASSET_CATEGORIES: readonly AssetCategory[] = [
  'ui',
  'blocks',
  'logic',
  'integrations',
  'recipes',
  'templates',
];

const DEFAULT_VERSION = '0.1.0';
const DEFAULT_LICENSE = 'MIT';
const LIBRARY_MANIFEST_PATH = 'simplify/library.json';

interface ResolvedOptions {
  readonly name: string;
  readonly description: string;
  readonly license: string;
  readonly category: string;
  readonly targetDir: string;
  readonly dryRun: boolean;
  readonly json: boolean;
}

function slugify(value: string): string {
  return value
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, 64);
}

function libraryId(name: string): string {
  const id = slugify(name);
  if (id.length === 0 || !/^[a-z0-9][a-z0-9-]*$/.test(id)) {
    return 'library';
  }
  return id;
}

function isAssetCategory(value: string): value is AssetCategory {
  return ASSET_CATEGORIES.includes(value as AssetCategory);
}

function resolveOptions(context: {
  readonly options: Readonly<Record<string, string | boolean>>;
}): ResolvedOptions {
  const options = context.options;

  if (typeof options.name !== 'string' || options.name.length === 0) {
    throw new CliError('Missing required option: --name.', 'MISSING_OPTION');
  }

  const name = options.name;
  const description =
    typeof options.description === 'string' && options.description.length > 0
      ? options.description
      : `A ${name} library for simplify.dev.`;
  const license =
    typeof options.license === 'string' && options.license.length > 0
      ? options.license
      : DEFAULT_LICENSE;
  const category =
    typeof options.category === 'string' && options.category.length > 0
      ? options.category
      : 'library';
  const targetDir =
    typeof options['target-dir'] === 'string' && options['target-dir'].length > 0
      ? options['target-dir']
      : process.cwd();
  const dryRun = options['dry-run'] === true;
  const json = options.json === true;

  return { name, description, license, category, targetDir, dryRun, json };
}

function buildLibraryManifest(options: ResolvedOptions): LibraryManifest {
  const publishing: PublishingConfiguration = {
    include: ['src/**', 'simplify/**', 'README.md', 'CHANGELOG.md'],
    exclude: ['**/node_modules/**', '**/.env*', '**/.simplify/**'],
  };

  const documentation: DocumentationReferences = {
    readme: 'README.md',
    examples: ['examples/'],
    changelog: 'CHANGELOG.md',
  };

  return {
    schemaVersion: 1,
    id: libraryId(options.name),
    name: options.name,
    description: options.description,
    version: DEFAULT_VERSION,
    license: options.license,
    assets: [`simplify/assets/${options.category}/example.asset.json`],
    publishing,
    documentation,
  };
}

function buildExampleAssetManifest(options: ResolvedOptions): AssetManifest {
  const exampleCategory = isAssetCategory(options.category) ? options.category : 'ui';

  return {
    schemaVersion: 1,
    id: `${exampleCategory}/example`,
    category: exampleCategory,
    name: 'Example Asset',
    description: 'Minimal asset authoring example.',
    version: DEFAULT_VERSION,
    publisher: 'local-author',
    status: 'community',
    license: options.license,
    targets: [{ language: 'typescript' }],
    implementations: [
      {
        id: 'example',
        target: { language: 'typescript' },
        mode: 'source',
        entry: 'src/example.ts',
      },
    ],
    installation: {
      modes: [
        {
          mode: 'source',
          files: [{ source: 'src/example.ts', target: 'src/example.ts' }],
        },
      ],
    },
    documentation: {
      readme: 'docs/getting-started.md',
      examples: ['examples/'],
      changelog: 'CHANGELOG.md',
    },
  };
}

function readmeContent(options: ResolvedOptions): string {
  return `# ${options.name}

${options.description}

## Library structure

This directory is a simplify.dev library scaffold generated by \`simplify library-init\`.

- \`simplify/library.json\` — library manifest. Declares identity, metadata, assets, and publishing configuration.
- \`simplify/assets/${options.category}/\` — asset manifests for the initial \`${options.category}\` category.
- \`src/\` — library source implementation.
- \`docs/\` — user and author documentation.
- \`examples/\` — usage examples for consumers.
- \`previews/\` — preview scenarios for UI assets.
- \`README.md\` — this file.
- \`CHANGELOG.md\` — change history following [Keep a Changelog](https://keepachangelog.com/).
- \`package.json\` — package metadata for publishing.

## Development workflow

1. Author asset manifests under \`simplify/assets/<category>/\`.
2. Register each asset manifest path in \`simplify/library.json\` under \`assets\`.
3. Validate manifests: \`simplify doctor\` (once wired) or validate against the simplify.dev schemas.
4. Push to GitHub. GitHub is the canonical source; simplify.dev owns registry metadata and distribution.
5. Publish through the simplify.dev publishing workflow. Published versions are immutable.

## GitHub-first publishing

This scaffold is designed for the GitHub-first workflow:

- Repository source code and history live on GitHub.
- simplify.dev registry metadata references the repository, commit SHA, and release tag.
- Connect this repository to simplify.dev to make the library discoverable and installable.

## Maintainers

Add maintainer entries to \`simplify/library.json\` under the optional \`maintainers\` field:

\`\`\`json
"maintainers": [
  { "name": "Your Name", "url": "https://github.com/you", "email": "you@example.com" }
]
\`\`\`

## License

${options.license}
`;
}

