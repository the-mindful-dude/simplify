interface PlannedFile {
  readonly path: string;
  readonly content: string;
}

interface Plan {
  readonly files: readonly PlannedFile[];
  readonly libraryManifest: LibraryManifest;
  readonly exampleAssetManifest: AssetManifest;
}

async function planFiles(options: ResolvedOptions): Promise<Plan> {
  const manifestPath = join(options.targetDir, LIBRARY_MANIFEST_PATH);
  const assetsDir = join(options.targetDir, 'simplify', 'assets', options.category);
  const assetManifestPath = join(assetsDir, 'example.asset.json');
  const assetsReadmePath = join(assetsDir, 'README.md');
  const srcIndexPath = join(options.targetDir, 'src', 'index.ts');
  const docsPath = join(options.targetDir, 'docs', 'getting-started.md');
  const examplesPath = join(options.targetDir, 'examples', 'README.md');
  const previewsPath = join(options.targetDir, 'previews', 'README.md');
  const readmePath = join(options.targetDir, 'README.md');
  const changelogPath = join(options.targetDir, 'CHANGELOG.md');
  const packageJsonPath = join(options.targetDir, 'package.json');

  const libraryManifest = buildLibraryManifest(options);
  const exampleAssetManifest = buildExampleAssetManifest(options);

  return {
    files: [
      { path: manifestPath, content: `${JSON.stringify(libraryManifest, null, 2)}\n` },
      {
        path: assetManifestPath,
        content: `${JSON.stringify(exampleAssetManifest, null, 2)}\n`,
      },
      { path: assetsReadmePath, content: assetsReadmeContent(options.category) },
      { path: srcIndexPath, content: assetIndexContent() },
      { path: docsPath, content: docsGettingStartedContent(options.name) },
      { path: examplesPath, content: examplesReadmeContent() },
      { path: previewsPath, content: previewsReadmeContent() },
      { path: readmePath, content: readmeContent(options) },
      { path: changelogPath, content: changelogContent() },
      { path: packageJsonPath, content: packageJsonContent(options) },
    ],
    libraryManifest,
    exampleAssetManifest,
  };
}

async function ensureWritable(filePaths: readonly string[]): Promise<void> {
  const existing: string[] = [];
  for (const filePath of filePaths) {
    try {
      await fs.access(filePath);
      existing.push(filePath);
    } catch {
      // Not present — safe to write.
    }
  }

  if (existing.length > 0) {
    throw new CliError(
      `Refusing to overwrite existing files:\n  ${existing.join('\n  ')}`,
      'FILE_EXISTS',
    );
  }
}

async function writeFileIfNeeded(filePath: string, content: string, json: boolean): Promise<void> {
  await fs.mkdir(dirname(filePath), { recursive: true });
  await fs.writeFile(filePath, content, { flag: 'wx' });
  info(`Created ${filePath}.`, json);
}

export const libraryInitCommand: Command = {
  name: 'library-init',
  description: 'Generate a simplify.dev library manifest and initial directory structure.',
  options: [
    {
      name: 'name',
      type: 'string',
      description: 'Library name (used to derive the library id).',
    },
    {
      name: 'description',
      type: 'string',
      description: 'Library description.',
    },
    {
      name: 'license',
      type: 'string',
      description: `License identifier (defaults to ${DEFAULT_LICENSE}).`,
    },
    {
      name: 'category',
      type: 'string',
      description: 'Initial asset category directory under simplify/assets/ (defaults to library).',
    },
    {
      name: 'target-dir',
      type: 'string',
      description: 'Target directory (defaults to the current working directory).',
    },
    {
      name: 'dry-run',
      type: 'boolean',
      description: 'Show what would happen without making changes.',
    },
  ],
  handler: async (context) => {
    const { dryRun, json } = context;
    const options = resolveOptions(context);

    info(
      dryRun
        ? `[dry-run] Would initialize library "${options.name}" in ${options.targetDir}.`
        : `Initializing library "${options.name}" in ${options.targetDir}...`,
      json,
    );

    const plan = await planFiles(options);

    const libraryValidation = validateLibraryManifest(plan.libraryManifest);
    if (!libraryValidation.valid) {
      const issues = libraryValidation.issues
        .map((issue) => `  - ${issue.path}: ${issue.message} (${issue.keyword})`)
        .join('\n');
      throw new CliError(`Generated library manifest is invalid:\n${issues}`, 'INVALID_MANIFEST');
    }

    const assetValidation = validateAssetManifest(plan.exampleAssetManifest);
    if (!assetValidation.valid) {
      const issues = assetValidation.issues
        .map((issue) => `  - ${issue.path}: ${issue.message} (${issue.keyword})`)
        .join('\n');
      throw new CliError(`Generated asset manifest is invalid:\n${issues}`, 'INVALID_MANIFEST');
    }

    if (dryRun) {
      for (const file of plan.files) {
        info(`[dry-run] Would create ${file.path}.`, json);
      }
      info('Dry-run complete. No changes were made.', json);
      return;
    }

    await ensureWritable(plan.files.map((file) => file.path));

    for (const file of plan.files) {
      await writeFileIfNeeded(file.path, file.content, json);
    }

    info(`Library "${options.name}" initialized.`, json);
    info(
      `Edit ${join(options.targetDir, LIBRARY_MANIFEST_PATH)} to add maintainers and assets.`,
      json,
    );
  },
};
