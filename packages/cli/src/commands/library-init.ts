function packageJsonContent(options: ResolvedOptions): string {
  return JSON.stringify(
    {
      name: libraryId(options.name),
      version: DEFAULT_VERSION,
      description: options.description,
      license: options.license,
      type: 'module',
      main: './dist/index.js',
      files: ['dist/', 'simplify/', 'src/', 'README.md', 'CHANGELOG.md'],
      scripts: {
        build: 'tsc -p tsconfig.json',
        lint: 'eslint src',
        test: 'vitest run',
      },
      repository: {
        type: 'git',
        url: '',
      },
      keywords: ['simplify-dev', 'library'],
      publishConfig: {
        access: 'public',
      },
    },
    null,
    2,
  );
}

